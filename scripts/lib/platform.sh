# shellcheck shell=bash
# shellcheck disable=SC2034  # values are consumed by the scripts that source this file
# Platform detection and portable primitives.
#
# Supported: macos, linux (incl. Ubuntu), wsl, windows (Git Bash / MSYS).
# Detection can be overridden with AGENT_POLICY_OS to exercise another branch,
# for example: AGENT_POLICY_OS=windows ./scripts/install.sh

[[ -n "${PLATFORM_LOADED:-}" ]] && return 0
PLATFORM_LOADED=1

detect_os() {
  if [[ -n "${AGENT_POLICY_OS:-}" ]]; then
    echo "$AGENT_POLICY_OS"
    return 0
  fi
  case "$(uname -s)" in
    Darwin) echo macos ;;
    Linux)
      if [[ -n "${WSL_DISTRO_NAME:-}" ]] || grep -qi microsoft /proc/version 2>/dev/null; then
        echo wsl
      else
        echo linux
      fi
      ;;
    MINGW*|MSYS*|CYGWIN*) echo windows ;;
    *) echo unknown ;;
  esac
}

OS="$(detect_os)"

# Windows symlinks need Developer Mode or elevation. Copying is the reliable path.
case "$OS" in
  windows) LINK_MODE="copy" ;;
  *)       LINK_MODE="symlink" ;;
esac

# In-place sed: GNU and BSD disagree about the argument.
sed_i() {
  if sed --version >/dev/null 2>&1; then
    sed -i "$@"
  else
    sed -i '' "$@"
  fi
}

has_rsync() { command -v rsync >/dev/null 2>&1; }

# Mirror src/ into dest/, preserving dest/.git and removing stale files.
# Minimal Ubuntu images may lack rsync, so fall back to a clean top-level swap.
mirror() {
  local src="$1" dest="$2"
  if has_rsync; then
    rsync -a --delete --exclude '.git/' "$src/" "$dest/"
  else
    find "$dest" -mindepth 1 -maxdepth 1 ! -name '.git' -exec rm -rf {} +
    cp -R "$src/." "$dest/"
  fi
}

# Marker present in every generated file. In copy mode it is the only way to
# tell our file from one the user wrote.
MARKER="GENERATED by scripts/build.sh"
is_managed() { [[ -f "$1" ]] && grep -q "$MARKER" "$1" 2>/dev/null; }

# Best-effort note about environments this install does not reach.
platform_note() {
  case "$OS" in
    wsl)
      echo "wsl: this install covers tools running inside WSL only."
      echo "     Windows-native tools with the same home directory need a separate run from Git Bash."
      ;;
    windows)
      echo "windows: installing by copy, because symlinks need Developer Mode."
      echo "         re-run install.sh --apply after every build.sh."
      ;;
    unknown)
      echo "unknown: platform not recognised; using symlink mode and generic paths."
      ;;
  esac
}
